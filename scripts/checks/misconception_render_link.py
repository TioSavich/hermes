#!/usr/bin/env python3
"""Regression check for the render-layer <-> misconception-registry join.

``knowledge/strategies/render/misconception_render_link.pl`` is generated by
``scripts/research/build_misconception_render_link.py``. It joins the render
layer's 44 deformation ids to the 2,448-name misconception registry through
citation bibkeys -- the only key the two sides share (standards are a dead
key; exact name equality joins only 5).

What this check holds:

  Regeneration.  The builder rerun is byte-identical to the committed file,
  twice.  A hand edit cannot pass, and neither can a source-file change
  nobody rebuilt for.

  The swipl re-derivation.  ``check_misconception_render_link/0`` recomputes
  the 44-id census and every citation/link/unlinked verdict from the SAME
  live predicates the builder read -- never by trusting this file's own
  facts -- and throws on the first disagreement. This check runs it and
  requires the PASS line.

  The census is exactly 44, exactly once.  Every id appears in exactly one of
  ``misconception_render_link/3`` or ``misconception_render_unlinked/2``,
  never both, never neither.

  too_vague never links.  No ``misconception_render_link/3`` row names
  ``too_vague`` as its RegistryName (2026-08 ruling: too_vague is never
  served as a misconception).

  Authored lane.  Five reviewed links emit ``via(authored)``; the angle row
  remains mechanical after regex widening. Reviewed refusals keep their named
  absence reason.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PATHS_PL = ROOT / "paths.pl"
BUILDER = ROOT / "scripts/research/build_misconception_render_link.py"
LINK_PL = ROOT / "knowledge/strategies/render/misconception_render_link.pl"

CITATION_RE = re.compile(
    r"(?m)^render_deformation_citation\((\w+), '((?:[^'\\]|\\.)*)',\s*\n"
    r"\s*source\('((?:[^'\\]|\\.)*)', .*?\)\)\.\s*$"
)
LINK_RE = re.compile(
    r"(?m)^misconception_render_link\((\w+), (\w+), via\((\w+(?:\([^)]*\))?)\)\)\."
)
UNLINKED_RE = re.compile(
    r"(?m)^misconception_render_unlinked\((\w+), reason\((.*)\)\)\.$"
)

EXPECTED_TOTAL = 44


def prolog(goal: str, timeout: int = 300) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["swipl", "-q", "-l", str(PATHS_PL), "-g", goal],
        cwd=ROOT, capture_output=True, text=True, timeout=timeout,
    )


def main() -> int:
    for path in (BUILDER, LINK_PL):
        if not path.exists():
            print(f"FAIL: {path} does not exist", file=sys.stderr)
            return 1

    errors: list[str] = []
    text = LINK_PL.read_text(encoding="utf-8")

    citations = CITATION_RE.findall(text)
    links = LINK_RE.findall(text)
    unlinked = UNLINKED_RE.findall(text)

    if not links and not unlinked:
        print("FAIL: no misconception_render_link/3 or "
              "misconception_render_unlinked/2 rows parsed", file=sys.stderr)
        return 1

    linked_ids = {render_id for render_id, _name, _via in links}
    unlinked_ids = {render_id for render_id, _reason in unlinked}
    all_ids = linked_ids | unlinked_ids

    if len(all_ids) != EXPECTED_TOTAL:
        errors.append(
            f"census has {len(all_ids)} distinct render ids across link + "
            f"unlinked rows, expected {EXPECTED_TOTAL}"
        )
    overlap = linked_ids & unlinked_ids
    if overlap:
        errors.append(f"ids both linked and unlinked: {sorted(overlap)}")

    for render_id, name, via in links:
        if name == "too_vague":
            errors.append(
                f"{render_id}: links to too_vague, which the "
                "misconception-under-erasure ruling says is never served"
            )
        if via == "name_equality" and render_id != name:
            errors.append(
                f"{render_id}: via(name_equality) but RegistryName is {name}, "
                "not the render id itself"
            )

    cited_ids = {render_id for render_id, _bibkey, _file in citations}
    for render_id, _name, via in links:
        if via.startswith("bibkey(") and render_id not in cited_ids:
            errors.append(
                f"{render_id}: links via a bibkey but has no "
                "render_deformation_citation/3 row"
            )

    via_counts: dict[str, int] = {}
    for _render_id, _name, via in links:
        key = via.split("(")[0]
        via_counts[key] = via_counts.get(key, 0) + 1
    expected_via = {"name_equality": 5, "bibkey": 1, "authored": 5}
    if via_counts != expected_via:
        errors.append(f"link lane counts are {via_counts}, expected {expected_via}")

    reason_counts: dict[str, int] = {}
    for _render_id, reason in unlinked:
        key = reason.split("(")[0]
        reason_counts[key] = reason_counts.get(key, 0) + 1
    expected_reasons = {
        "no_registry_bibkey": 9,
        "no_literature_signal": 23,
        "prefilter_rejected": 1,
    }
    if reason_counts != expected_reasons:
        errors.append(
            f"unlinked reason counts are {reason_counts}, expected {expected_reasons}"
        )

    # --- the swipl re-derivation ---
    check = prolog(
        "use_module(render(misconception_render_link)), "
        "( catch(check_misconception_render_link, E, "
        "  (print_message(error, E), halt(1))) "
        "-> halt(0) ; halt(1) )."
    )
    if check.returncode != 0:
        errors.append(
            "check_misconception_render_link/0 did not pass:\n"
            f"{check.stdout.strip()}\n{check.stderr.strip()}"
        )
    elif "PASS check_misconception_render_link" not in check.stdout:
        errors.append(
            f"check_misconception_render_link/0 exited 0 but printed no PASS "
            f"line:\n{check.stdout.strip()}"
        )

    # --- regeneration: byte-identical, twice ---
    import shutil
    import tempfile

    workdir = Path(tempfile.mkdtemp(prefix="misconception-render-link-"))
    try:
        first = workdir / "one.pl"
        second = workdir / "two.pl"
        for target in (first, second):
            out = subprocess.run(
                [sys.executable, str(BUILDER), "--output", str(target)],
                cwd=ROOT, capture_output=True, text=True, timeout=600,
            )
            if out.returncode != 0:
                errors.append(f"builder failed: {out.stderr.strip()[:500]}")
                break
        else:
            if first.read_bytes() != LINK_PL.read_bytes():
                errors.append(
                    "the builder rerun is not byte-identical to the "
                    f"committed {LINK_PL.relative_to(ROOT)}; run "
                    f"python3 {BUILDER.relative_to(ROOT)}"
                )
            if first.read_bytes() != second.read_bytes():
                errors.append("two builder runs disagree")
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    if errors:
        print(f"FAIL: {len(errors)} problem(s):", file=sys.stderr)
        for error in errors[:20]:
            print(f"  - {error}", file=sys.stderr)
        if len(errors) > 20:
            print(f"  ... and {len(errors) - 20} more", file=sys.stderr)
        return 1

    print(f"PASS regeneration: {BUILDER.name} rerun is byte-identical, twice")
    print("PASS check_misconception_render_link/0 re-derived every claim")
    print(f"PASS census: {len(all_ids)} render ids, each linked xor unlinked")
    print("PASS no too_vague links; authored lane and named refusals match")
    print()
    print(f"render ids                : {len(all_ids)}")
    print(f"citation rows             : {len(citations)} over "
          f"{len(cited_ids)} render ids")
    print(f"link rows                 : {len(links)} over "
          f"{len(linked_ids)} render ids")
    print(f"  by via                  : {via_counts}")
    print(f"unlinked render ids       : {len(unlinked_ids)}")
    print(f"  by reason               : {reason_counts}")
    print()
    print("PASS misconception_render_link check")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
