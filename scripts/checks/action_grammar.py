#!/usr/bin/env python3
"""Regression check for the grammar layer over the action alphabet.

``knowledge/strategies/action_grammar.pl`` is generated by
``scripts/research/build_action_grammar.py`` from three sources: the canonical
alphabet, the strategy transition tables, and the discursive genre in
``knowledge/discourse/commitment_automata.pl``.  This check holds it to what it
claims.

  Regeneration.  The builder rerun into a temporary directory is byte-identical
  to the committed file.  A hand edit to the derived rows cannot pass.

  Strict load.  Both new modules load clean under SWI with warnings fatal.

  Coverage.  Every machine in both genres has exactly one machine_grammar row;
  every arc a row names is declared; every declared arc and phrase is carried by
  at least one machine, so neither table holds a dead name.

  The discursive genre is well formed.  Every machine's declared actions match
  its edges, every state is reachable from the start, an accepting state is
  reachable, no state-action pair has two targets, and every action has a
  canonical_action/3 row of the right genre.

  The stance projection is faithful.  Each row's stances list is the machine's
  own word rewritten through action_register/4, and its arc is that list with
  runs collapsed.  This is recomputed here from the tables rather than trusted.

  The phrase factorization is faithful.  Concatenating each row's phrases, with
  named phrases expanded back to their sequences, reproduces the machine's
  action word exactly.

  Verdicts match the corpus.  Every ``stop`` row is checked against the machines
  that carry that token: if any of them ends on a step that is not deforming,
  the stop is wrong and the check fails.

  The unmodelled edges are counted, not hidden.  The discursive genre's
  provenance splits into edges a predicate here carries and edges only the
  literature carries; the second count is reported every run.
"""
from __future__ import annotations

import collections
import itertools
import py_compile
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PATHS_PL = ROOT / "paths.pl"
BUILDER = ROOT / "scripts/research/build_action_grammar.py"
GRAMMAR = ROOT / "knowledge/strategies/action_grammar.pl"
MAP_PATH = ROOT / "knowledge/strategies/action_vocabulary_map.pl"
STRATEGY_TABLES = ROOT / "knowledge/strategies/transition_tables"
DISCOURSE = ROOT / "knowledge/discourse/commitment_automata.pl"

VERDICTS = ("stop", "watch", "continue")
STANCES = ("conserving", "deforming", "neutral")

TUPLE_RE = re.compile(
    r"(?m)^automaton_tuple\((\w+),\s*(\w+),\s*states\(\[([^\]]*)\]\),\s*"
    r"actions\(\[([^\]]*)\]\),\s*start\((\w+)\),\s*accepting\(\[([^\]]*)\]\)\)")
TRANS_RE = re.compile(
    r"(?m)^automaton_transition\((\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*"
    r"provenance\((.*?)\)\)\.")
MAPS_RE = re.compile(r"(?m)^action_maps\((\w+), (\w+), (\w+), (\w+),")
AXES_RE = re.compile(
    r"(?m)^action_register\((\w+), genre\((\w+)\), register\((\w+)\), stance\((\w+)\)\)")
CANON_RE = re.compile(r"(?m)^canonical_action\((\w+), gloss\(")
PHRASE_RE = re.compile(r"(?m)^action_phrase\((\w+), sequence\(\[([^\]]*)\]\)")
ARC_RE = re.compile(r"(?m)^normative_arc\((\w+), stances\(\[([^\]]*)\]\)")
GRAMMAR_RE = re.compile(
    r"(?m)^machine_grammar\((\w+), (\w+), (\w+), arc\((\w+)\),\s*"
    r"phrases\(\[([^\]]*)\]\),\s*stances\(\[([^\]]*)\]\)\)")
LICENSE_RE = re.compile(
    r"(?m)^interruption_license\((\w+), (\w+), after\((\w+)\), verdict\((\w+)\)")


def items(text: str) -> list[str]:
    return [part.strip() for part in text.split(",") if part.strip()]


def read_alphabet() -> tuple[dict, set]:
    text = MAP_PATH.read_text(encoding="utf-8")
    axes = {name: (genre, register, stance)
            for name, genre, register, stance in AXES_RE.findall(text)}
    canonical = set(CANON_RE.findall(text))
    projection = {(f, s, l): c for f, s, l, c in MAPS_RE.findall(text)}
    return {"axes": axes, "projection": projection, "canonical": canonical}, canonical


def read_machines(projection: dict):
    """Return machines with their canonical words, plus the discursive edge census."""
    sources = [(p, "computational") for p in sorted(STRATEGY_TABLES.glob("*.pl"))]
    sources.append((DISCOURSE, "discursive"))
    declared, edges, genre, starts, accepting = {}, collections.defaultdict(set), {}, {}, {}
    provenance = collections.Counter()
    for path, kind in sources:
        text = path.read_text(encoding="utf-8")
        for family, signature, states, actions, start, accepts in (
                m.groups() for m in TUPLE_RE.finditer(text)):
            key = (family, signature)
            declared[key] = (items(states), items(actions))
            starts[key], accepting[key] = start, set(items(accepts))
            genre[key] = kind
        for family, signature, source, action, target, prov in (
                m.groups() for m in TRANS_RE.finditer(text)):
            key = (family, signature)
            edges[key].add((source, action, target))
            if kind == "discursive":
                provenance["grounded" if "grounded(" in prov else "unmodelled"] += 1
    words = {}
    for key in sorted(edges):
        routes = collections.defaultdict(list)
        for source, action, target in sorted(edges[key]):
            canonical = projection.get((key[0], key[1], action), action)
            if canonical not in [a for a, _ in routes[source]]:
                routes[source].append((canonical, target))
        sequence, state, seen = [], starts[key], {starts[key]}
        while True:
            outgoing = routes.get(state, [])
            if len(outgoing) != 1:
                break
            action, target = outgoing[0]
            sequence.append(action)
            if target in seen:
                break
            seen.add(target)
            state = target
        words[key] = tuple(sequence)
    return declared, edges, genre, starts, accepting, words, provenance


def check_discursive(declared, edges, starts, accepting, axes, canonical) -> list[str]:
    errors = []
    for key, rows in sorted(edges.items()):
        if key[0] != "discourse":
            continue
        states, actions = declared[key]
        where = f"{key[0]}/{key[1]}"
        if set(a for _, a, _ in rows) != set(actions):
            errors.append(f"{where}: declared actions and edge actions differ")
        touched = {s for s, _, _ in rows} | {t for _, _, t in rows}
        if touched != set(states):
            errors.append(f"{where}: declared states and edge states differ")
        destinations = collections.defaultdict(set)
        for source, action, target in rows:
            destinations[(source, action)].add(target)
        for pair, targets in destinations.items():
            if len(targets) > 1:
                errors.append(f"{where}: {pair} has two targets {sorted(targets)}")
        routes = collections.defaultdict(list)
        for source, action, target in rows:
            routes[source].append(target)
        reached, stack = {starts[key]}, [starts[key]]
        while stack:
            for target in routes.get(stack.pop(), []):
                if target not in reached:
                    reached.add(target)
                    stack.append(target)
        if set(states) - reached:
            errors.append(f"{where}: unreachable states {sorted(set(states) - reached)}")
        if not accepting[key] & reached:
            errors.append(f"{where}: no accepting state is reachable")
        for _, action, _ in rows:
            if action not in canonical:
                errors.append(f"{where}: {action} has no canonical_action/3 row")
            elif action in axes and axes[action][0] not in ("discursive", "computational"):
                errors.append(f"{where}: {action} carries genre {axes[action][0]}")
    return errors


def check_grammar(alphabet, genre, words) -> tuple[list[str], dict]:
    text = GRAMMAR.read_text(encoding="utf-8")
    axes = alphabet["axes"]
    phrases = {name: tuple(items(body)) for name, body in PHRASE_RE.findall(text)}
    arcs = {name: tuple(items(body)) for name, body in ARC_RE.findall(text)}
    rows = [(g, f, s, arc, items(ph), items(st))
            for g, f, s, arc, ph, st in GRAMMAR_RE.findall(text)]
    licenses = LICENSE_RE.findall(text)
    errors: list[str] = []

    seen = collections.Counter((f, s) for _, f, s, _, _, _ in rows)
    for key, count in seen.items():
        if count > 1:
            errors.append(f"{key[0]}/{key[1]}: {count} machine_grammar rows")
    for key in sorted(set(words) - set(seen)):
        errors.append(f"{key[0]}/{key[1]}: no machine_grammar row")
    for key in sorted(set(seen) - set(words)):
        errors.append(f"{key[0]}/{key[1]}: machine_grammar row for no machine")

    arc_use, phrase_use = collections.Counter(), collections.Counter()
    for g, family, signature, arc, phrase_list, stance_list in rows:
        key = (family, signature)
        where = f"{family}/{signature}"
        if key in genre and genre[key] != g:
            errors.append(f"{where}: row says genre {g}, tables say {genre[key]}")
        if arc not in arcs:
            errors.append(f"{where}: arc {arc} is not declared")
            continue
        arc_use[arc] += 1
        word = words.get(key, ())
        expected_stances = [axes[a][2] for a in word if a in axes]
        if len(expected_stances) != len(word):
            errors.append(f"{where}: an action has no action_register/4 row")
            continue
        if stance_list != expected_stances:
            errors.append(f"{where}: stances row does not match the machine's word")
        collapsed = [k for k, _ in itertools.groupby(stance_list)]
        if tuple(collapsed) != arcs[arc]:
            errors.append(f"{where}: arc {arc} is not this row's collapsed stance word")
        rebuilt: list[str] = []
        for part in phrase_list:
            if part in phrases:
                rebuilt.extend(phrases[part])
                phrase_use[part] += 1
            else:
                rebuilt.append(part)
        if tuple(rebuilt) != word:
            errors.append(f"{where}: the phrases row does not rebuild the machine's word")
        for stance in stance_list:
            if stance not in STANCES:
                errors.append(f"{where}: {stance} is not a stance")

    for name in sorted(set(arcs) - set(arc_use)):
        errors.append(f"arc {name} is declared but carried by no machine")
    for name in sorted(set(phrases) - set(phrase_use)):
        errors.append(f"phrase {name} is declared but carried by no machine")

    ends_deforming = {
        key: bool(word) and axes[word[-1]][2] == "deforming"
        for key, word in words.items() if all(a in axes for a in word)
    }
    holders = collections.defaultdict(list)
    for key, word in words.items():
        for action in set(word):
            holders[action].append(key)
    for g, action, context, verdict in licenses:
        if verdict not in VERDICTS:
            errors.append(f"{action}: verdict {verdict} is not one of {VERDICTS}")
        if action not in axes:
            errors.append(f"{action}: no action_register/4 row")
            continue
        if axes[action][0] != g:
            errors.append(f"{action}: license says genre {g}, alphabet says {axes[action][0]}")
        if verdict != "stop":
            continue
        if context == "any_context":
            carriers = holders[action]
        else:
            carriers = [k for k, w in words.items()
                        if any(w[i] == context and w[i + 1] == action
                               for i in range(len(w) - 1))]
        survivors = sorted(f"{k[0]}/{k[1]}" for k in carriers if not ends_deforming.get(k, True))
        if survivors:
            errors.append(
                f"{action} after {context} is a stop, but these machines carrying "
                f"it do not end on a deforming step: {survivors}")
        if not carriers:
            errors.append(f"{action} after {context} is a stop with no carrier")

    summary = {
        "phrases": len(phrases),
        "arcs": len(arcs),
        "rows": len(rows),
        "licenses": len(licenses),
        "verdicts": dict(sorted(collections.Counter(v for *_, v in licenses).items())),
        "arc_use": arc_use,
        "phrase_use": phrase_use,
        "words": words,
        "axes": axes,
        "genre": genre,
    }
    return errors, summary


def run_strict_load(alias: str) -> None:
    goal = f"user:use_module(strategies({alias}), []), halt."
    result = subprocess.run(
        ["swipl", "-q", "--on-warning=status", "--on-error=status",
         "-l", str(PATHS_PL), "-g", goal],
        cwd=ROOT, capture_output=True, text=True, timeout=180)
    if result.returncode != 0:
        raise RuntimeError(f"strict SWI load of strategies({alias}) failed "
                           f"(exit {result.returncode}):\n{result.stdout}\n{result.stderr}")


def run_consult(path: Path) -> None:
    result = subprocess.run(
        ["swipl", "-q", "--on-warning=status", "--on-error=status",
         "-g", f"consult('{path.relative_to(ROOT)}'), halt."],
        cwd=ROOT, capture_output=True, text=True, timeout=180)
    if result.returncode != 0:
        raise RuntimeError(f"strict SWI consult of {path.name} failed "
                           f"(exit {result.returncode}):\n{result.stdout}\n{result.stderr}")


def check_regeneration(workdir: Path) -> list[str]:
    target = workdir / "action_grammar.pl"
    result = subprocess.run(
        [sys.executable, str(BUILDER), "--output", str(target)],
        cwd=ROOT, capture_output=True, text=True, timeout=600)
    if result.returncode != 0:
        return [f"builder failed (exit {result.returncode}): {result.stderr.strip()}"]
    if target.read_bytes() != GRAMMAR.read_bytes():
        return ["the builder rerun is not byte-identical to the committed "
                f"{GRAMMAR.relative_to(ROOT)}; run "
                f"python3 {BUILDER.relative_to(ROOT)}"]
    second = workdir / "action_grammar_second.pl"
    subprocess.run([sys.executable, str(BUILDER), "--output", str(second)],
                   cwd=ROOT, capture_output=True, text=True, timeout=600)
    if second.read_bytes() != target.read_bytes():
        return ["two builder runs disagree"]
    return []


def main() -> int:
    for path in (BUILDER, GRAMMAR, MAP_PATH, DISCOURSE):
        if not path.exists():
            print(f"FAIL: {path} does not exist", file=sys.stderr)
            return 1
    errors: list[str] = []
    try:
        alphabet, canonical = read_alphabet()
        declared, edges, genre, starts, accepting, words, provenance = read_machines(
            alphabet["projection"])
    except (ValueError, OSError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1

    errors += check_discursive(declared, edges, starts, accepting, alphabet["axes"], canonical)
    grammar_errors, summary = check_grammar(alphabet, genre, words)
    errors += grammar_errors

    for path in (BUILDER, Path(__file__)):
        try:
            py_compile.compile(str(path), doraise=True)
        except py_compile.PyCompileError as exc:
            errors.append(f"{path.name} does not compile: {exc}")

    workdir = Path(tempfile.mkdtemp(prefix="action-grammar-"))
    try:
        run_consult(DISCOURSE)
        run_strict_load("action_grammar")
        run_strict_load("action_vocabulary_map")
        errors += check_regeneration(workdir)
    except (RuntimeError, OSError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        shutil.rmtree(workdir, ignore_errors=True)
        return 1
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    if errors:
        print(f"FAIL: {len(errors)} problem(s):", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1

    axes = summary["axes"]
    computational = [k for k, g in genre.items() if g == "computational"]
    discursive = [k for k, g in genre.items() if g == "discursive"]
    cross = collections.defaultdict(set)
    for g, family, signature, arc, _, _ in GRAMMAR_RE.findall(
            GRAMMAR.read_text(encoding="utf-8")):
        cross[arc].add(g)
    cross_arcs = sorted(a for a, gs in cross.items() if len(gs) > 1)

    print("PASS strict SWI load of the discursive genre and both new modules")
    print(f"PASS regeneration: {BUILDER.name} rerun is byte-identical, twice")
    print(f"PASS coverage: {summary['rows']} machine_grammar rows for "
          f"{len(words)} machines ({len(computational)} computational, "
          f"{len(discursive)} discursive); no arc or phrase unused")
    print("PASS the discursive genre is deterministic, reachable, and terminating")
    print("PASS every stances row is its machine's word through action_register/4, "
          "and every arc is that row collapsed")
    print("PASS every phrases row rebuilds its machine's action word exactly")
    print(f"PASS verdicts: every stop row survives its carriers "
          f"({summary['verdicts']})")
    print()
    print("Compression up the layers:")
    print(f"  machines, both genres            : {len(words)}")
    print(f"  distinct canonical action words  : {len(set(words.values()))}")
    print(f"  distinct stance words            : "
          f"{len({tuple(axes[a][2] for a in w) for w in words.values()})}")
    print(f"  normative arcs                   : {summary['arcs']}")
    print(f"  arcs spelled by both genres      : {len(cross_arcs)}  {cross_arcs}")
    print()
    print("Phrase layer (the within-genre idioms):")
    print(f"  phrases named                    : {summary['phrases']}")
    print(f"  phrase instances across machines : {sum(summary['phrase_use'].values())}")
    print("  most carried:")
    for name, count in summary["phrase_use"].most_common(6):
        print(f"      {count:3d}  {name}")
    print()
    print("Discursive genre provenance:")
    print(f"  edges a predicate here carries   : {provenance['grounded']}")
    print(f"  edges only the literature carries: {provenance['unmodelled']}")
    print()
    print("Normative arcs by machine count:")
    for arc, count in summary["arc_use"].most_common():
        tag = " both genres" if arc in cross_arcs else ""
        print(f"  {count:4d}  {arc}{tag}")
    print()
    print("PASS action_grammar check")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
